"""Which CE1 renderings and engine pairs a live CE-matrix run certified (design §4.4).

``apps/api/data/parity_ce_certification.json`` is generated by the
``parity-ce-matrix`` CI job (``scripts/gen_parity_ce_certification.py``) from
the cases that passed on live engines. A scan records, per in-engine column,
whether its kind is certified for the server pair it actually talked to (the
MariaDB leg is told apart from MySQL by ``VERSION()``).

Phase 2 records the answer in the evidence only. Phase 3 enforces it: an
uncertified kind is compared by streamed fingerprint, and nothing may say
"proven" on the strength of a rendering no live engine executed.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

PATH = Path(__file__).resolve().parents[2] / "data" / "parity_ce_certification.json"


@lru_cache(maxsize=1)
def load() -> dict[str, Any]:
    try:
        return json.loads(PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"pairs": {}, "engines": {}}


def _family(server: str) -> str:
    for name in ("postgresql", "mariadb", "mysql", "sqlserver", "sqlite"):
        if str(server or "").startswith(name):
            return name
    return str(server or "")


def assess(plan: Any, source_server: str, destination_server: str) -> dict[str, Any]:
    """Certification of each in-engine column for this server pair."""
    src, dst = _family(source_server), _family(destination_server)
    data = load()
    certified: set[str] = set()
    run = data.get("matrix_run") or ""
    for pair in (data.get("pairs") or {}).values():
        if pair.get("source_family") == src and pair.get("destination_family") == dst:
            certified |= set(pair.get("kinds") or [])
    reference = src == dst == "sqlite"  # the reference engine runs the Python encoder itself
    columns = []
    for col in plan.engine_columns:
        ok = reference or (col.kind in certified and col.kind != "native")
        columns.append({"column": col.target, "kind": col.kind, "certified": ok})
    return {
        "pair": f"{src}->{dst}",
        "source_server": source_server,
        "destination_server": destination_server,
        "matrix_run": run,
        "all_certified": all(c["certified"] for c in columns),
        "columns": columns,
        "enforced": False,
    }
