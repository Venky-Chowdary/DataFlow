"""Recreate the source's key *generator* on a create-new destination.

Copying key values is not the same as copying the key. A source column declared
``GENERATED BY DEFAULT AS IDENTITY`` / ``AUTO_INCREMENT`` / ``IDENTITY(1,1)``
lands as a plain integer unless the generator is emitted too, and then the
client's first application insert after cutover fails — the row values are
identical, every checksum matches, and the table is still unusable. Row-level
proof cannot see this, because the defect lives in the destination's DDL.

Two failure modes, both real and both silent:

- *generator dropped* — the destination column has no default at all, so
  ``INSERT INTO t (name) VALUES (...)`` raises NOT NULL;
- *generator not advanced* — the column generates, but from 1, so the first
  insert collides with a migrated row. The counter itself is aligned after the
  load by :mod:`services.identity_watermark`; this module only ensures there is
  a generator for it to align.

Fail-closed rules:

- carry only where the destination engine can express the generator *and*
  accept the explicit key values the load is about to write. Everything else is
  reported ``unsupported`` with the engine's reason — never emitted as a plain
  column that looks carried.
- ``GENERATED ALWAYS`` is relaxed to ``BY DEFAULT`` because the load must write
  the source's own key values. That is a semantic change, so it is reported as
  such rather than claimed as a faithful carry.
- a generator and a ``DEFAULT`` on the same column contradict each other; the
  generator wins and the default is reported as dropped.
"""

