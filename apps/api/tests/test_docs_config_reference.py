"""docs/operate/configuration.md lists every environment flag the code reads.

The table is generated by ``docs/tools/gen_config_reference.py`` from a syntax
scan of the runtime code. These tests fail when a flag is read in code and the
page was not regenerated, which is the drift the page exists to prevent.
"""

from __future__ import annotations

import importlib.util
import os
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
GENERATOR = REPO_ROOT / "docs" / "tools" / "gen_config_reference.py"
PAGE = REPO_ROOT / "docs" / "operate" / "configuration.md"
REGENERATE = "run `python docs/tools/gen_config_reference.py` from the repository root"


@pytest.fixture(scope="module")
def gen():
    spec = importlib.util.spec_from_file_location("gen_config_reference", GENERATOR)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    import sys

    sys.modules[spec.name] = module  # dataclasses resolve annotations through sys.modules
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def scanned(gen):
    flags, dynamic = gen.collect()
    return flags, dynamic


def test_every_flag_read_in_code_is_in_the_table(gen, scanned) -> None:
    flags, _ = scanned
    listed = gen.table_flag_names(PAGE.read_text(encoding="utf-8"))
    missing = sorted(set(flags) - listed)
    assert not missing, f"flags read in code but missing from {PAGE.name}: {missing}; {REGENERATE}"


def test_table_lists_no_flag_the_code_stopped_reading(gen, scanned) -> None:
    flags, _ = scanned
    listed = gen.table_flag_names(PAGE.read_text(encoding="utf-8"))
    stale = sorted(listed - set(flags))
    assert not stale, f"{PAGE.name} lists flags no code reads: {stale}; {REGENERATE}"


def test_scan_finds_the_flags_the_product_depends_on(scanned) -> None:
    """A scanner that silently finds nothing would make the two tests above pass."""
    flags, _ = scanned
    assert len(flags) > 300
    for key in ("AUTH_SECRET", "SECRETS_KEY", "MULTI_REPLICA", "PROCESS_ROLE", "DATA_DIR"):
        assert key in flags and flags[key].brand_read, key
    # Read through a local wrapper (``_int_env("JOB_ORPHAN_MAX_RECLAIMS", ...)``).
    assert flags["JOB_ORPHAN_MAX_RECLAIMS"].brand_read
    # Read under one exact name through a module constant (``os.getenv(EXPOSE_ENV)``):
    # only the DATAFLOW_ spelling works.
    assert flags["EXPOSE_ERROR_DETAIL"].accepted_names() == ["DATAFLOW_EXPOSE_ERROR_DETAIL"]
    # Read through getenv_brand with the legacy spelling: both names work.
    assert flags["PUBLIC_RATE_LIMIT"].accepted_names() == [
        "DATAWRAP_PUBLIC_RATE_LIMIT",
        "DATAFLOW_PUBLIC_RATE_LIMIT",
    ]
    # Reached through a literal tuple that is looped over.
    assert "MONGO_PRIVATE_URL" in flags
    # A pydantic settings alias.
    assert "RETRY_MAX_ATTEMPTS" in flags


def test_a_new_flag_is_caught(gen, tmp_path, monkeypatch) -> None:
    """Prove the check bites: a flag added to code is reported as missing."""
    fake_root = tmp_path / "repo"
    module_dir = fake_root / "apps" / "api" / "services"
    module_dir.mkdir(parents=True)
    (module_dir / "new_feature.py").write_text(
        "import os\n"
        "from services.brand_env import getenv_brand\n\n"
        "def limit():\n"
        '    """How many widgets one run may make."""\n'
        '    return int(getenv_brand("WIDGET_LIMIT_FOR_DRIFT_TEST", "7"))\n\n'
        "def legacy():\n"
        '    return os.getenv("DATAFLOW_ONLY_LEGACY_FOR_DRIFT_TEST")\n',
        encoding="utf-8",
    )
    monkeypatch.setattr(gen, "REPO_ROOT", fake_root)
    flags, _ = gen.collect()
    assert flags["WIDGET_LIMIT_FOR_DRIFT_TEST"].accepted_names() == [
        "DATAWRAP_WIDGET_LIMIT_FOR_DRIFT_TEST",
        "DATAFLOW_WIDGET_LIMIT_FOR_DRIFT_TEST",
    ]
    assert flags["WIDGET_LIMIT_FOR_DRIFT_TEST"].defaults == {"7"}
    assert flags["ONLY_LEGACY_FOR_DRIFT_TEST"].accepted_names() == ["DATAFLOW_ONLY_LEGACY_FOR_DRIFT_TEST"]
    listed = gen.table_flag_names(PAGE.read_text(encoding="utf-8"))
    assert "WIDGET_LIMIT_FOR_DRIFT_TEST" not in listed


def test_no_credential_default_is_printed(gen, scanned) -> None:
    flags, _ = scanned
    checked = 0
    for flag in flags.values():
        if not gen._SECRET_NAME.search(flag.key):
            continue
        cell = gen._default_cell(flag)
        literal = flag.defaults - {"unset", '""', "required", "computed"}
        if literal:
            checked += 1
            assert cell == "set in code (not shown)", flag.key
            for value in literal:
                assert value not in cell, flag.key
    assert checked, "expected at least one credential-shaped flag with a default in code"


def test_page_keeps_its_hand_written_sections() -> None:
    text = PAGE.read_text(encoding="utf-8")
    for heading in ("## The prefix rule", "## What production requires", "## Not covered", "## Verified against"):
        assert heading in text
    assert os.path.exists(REPO_ROOT / "docs" / "tools" / "config_descriptions.json")
