"""UX-26: a generator attribute on the destination type is not a type change.

MySQL's catalog reports an identity key as ``BIGINT AUTO_INCREMENT`` (the audit's
live destination). The Map grader read the attribute as part of the storage type
and graded ``INT4 → BIGINT AUTO_INCREMENT`` as lossy, so Auto-map raised a
Risk Contract on a widening. The attribute says who fills the column, not how a
value is stored: the pair grades exactly as ``INT4 → BIGINT``.
"""

from __future__ import annotations

import pytest

from services.mapping_type_compat import grade_type_pair


@pytest.mark.parametrize(
    "target",
    [
        "BIGINT AUTO_INCREMENT",
        "BIGINT NOT NULL AUTO_INCREMENT",
        "bigint auto_increment",
        "BIGINT GENERATED ALWAYS AS IDENTITY",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY",
        "BIGINT IDENTITY(1,1)",
    ],
)
def test_widening_into_an_identity_column_is_safe(target: str) -> None:
    graded = grade_type_pair("INT4", target, dest_db="mysql")
    assert graded["verdict"] == "safe", graded
    assert graded["requires_risk_contract"] is False
    # The row still names the type the destination reported.
    assert graded["target_type"] == target


def test_narrowing_into_an_identity_column_is_still_lossy() -> None:
    graded = grade_type_pair("INT8", "INT AUTO_INCREMENT", dest_db="mysql")
    assert graded["verdict"] == "lossy", graded
    assert any(r["kind"] == "narrowing" for r in graded["reasons"])


def test_collation_is_kept_for_the_charset_verdict() -> None:
    # COLLATE is not a generator attribute: the grade must still see it.
    assert grade_type_pair("CHAR(2)", "CHAR(2) COLLATE utf8mb4_bin", dest_db="mysql")["verdict"] == "safe"
    assert grade_type_pair("TIMESTAMPTZ", "DATETIME(6)", dest_db="mysql")["verdict"] == "lossy"
