"""docs/use/mcp.md lists every registered tool with its permission and effect.

The table is generated by ``docs/tools/gen_mcp_tools.py`` from the registry
Pilot and MCP share. Tool descriptions are not compared, so rewording one does
not fail this test; adding, removing or re-gating a tool does.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
GENERATOR = REPO_ROOT / "docs" / "tools" / "gen_mcp_tools.py"
PAGE = REPO_ROOT / "docs" / "use" / "mcp.md"
REGENERATE = "run `python docs/tools/gen_mcp_tools.py` from the repository root"


@pytest.fixture(scope="module")
def gen():
    spec = importlib.util.spec_from_file_location("gen_mcp_tools", GENERATOR)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def test_table_matches_the_registry(gen) -> None:
    listed = gen.table_rows(PAGE.read_text(encoding="utf-8"))
    expected = {r["name"]: (r["permission"], r["effect"]) for r in gen.collect_rows()}
    assert set(expected) - set(listed) == set(), f"tools missing from {PAGE.name}; {REGENERATE}"
    assert set(listed) - set(expected) == set(), f"{PAGE.name} lists tools that no longer exist; {REGENERATE}"
    changed = sorted(n for n in expected if listed[n] != expected[n])
    assert not changed, f"permission or effect changed for {changed}; {REGENERATE}"


def test_every_mutating_tool_is_documented_as_staged(gen) -> None:
    rows = gen.collect_rows()
    assert rows, "the registry returned no tools"
    for row in rows:
        assert row["staged"] == ("yes" if row["effect"] == "mutate" else "no"), row["name"]
    names = {r["name"] for r in rows}
    assert {"confirm_action", "start_transfer", "explain_parity"} <= names


def test_a_new_tool_is_caught(gen, monkeypatch) -> None:
    from src.ai.copilot import tools as tool_registry

    extra = {"name": "drift_probe_tool", "description": "Not real.", "input_schema": {"type": "object"}}
    monkeypatch.setattr(tool_registry, "TOOL_DEFINITIONS", [*tool_registry.TOOL_DEFINITIONS, extra])
    rows = {r["name"]: r for r in gen.collect_rows()}
    assert rows["drift_probe_tool"]["permission"].startswith("admin only")
    assert "drift_probe_tool" not in gen.table_rows(PAGE.read_text(encoding="utf-8"))
