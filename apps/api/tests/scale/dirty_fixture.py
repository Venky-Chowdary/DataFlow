@dataclass(frozen=True)
class FormatSpec:
    """A file format in the matrix: how to write it and how to read it back."""

    name: str          # engine ``format`` for a file source
    suffix: str        # filename suffix
    export_format: str  # engine ``format`` for a file_export destination ('' = none)
    typed: bool = False  # container carries native types (not text)


FORMATS: dict[str, FormatSpec] = {
    "csv": FormatSpec("csv", ".csv", "csv"),
    "tsv": FormatSpec("tsv", ".tsv", "tsv"),
    "psv": FormatSpec("csv", ".psv", "csv"),
    "scsv": FormatSpec("csv", ".csv", "csv"),
    "json": FormatSpec("json", ".json", "json"),
    "jsonl": FormatSpec("jsonl", ".jsonl", "jsonl"),
    "ndjson": FormatSpec("ndjson", ".ndjson", "ndjson"),
    "parquet": FormatSpec("parquet", ".parquet", "parquet", typed=True),
    "avro": FormatSpec("avro", ".avro", "avro", typed=True),
    "orc": FormatSpec("orc", ".orc", "orc", typed=True),
    "excel": FormatSpec("excel", ".xlsx", "excel"),
    "xml": FormatSpec("xml", ".xml", "xml"),
    "csv_gz": FormatSpec("csv", ".csv.gz", ""),
    "fixed_width": FormatSpec("fixed_width", ".txt", ""),
    "yaml": FormatSpec("yaml", ".yaml", ""),
}

_DELIMITERS = {"csv": ",", "tsv": "\t", "psv": "|", "scsv": ";"}

#: Fixed-width layout (column, width) — declared, because a fixed-width file
#: without a declared layout is unparseable by definition.
FIXED_WIDTH_LAYOUT: tuple[tuple[str, int], ...] = (
    ("id", 8),
    ("acct_code", 10),
    ("amount", 16),
    ("qty", 6),
    ("note", 40),
    ("unicode_name", 20),
    ("created_at", 22),
    ("dob_mixed", 12),
    ("flag", 6),
    ("null_empty", 8),
    ("null_token", 8),
)


def _open_text(path: Path, encoding: str, *, compress: bool, bom: bool):
    if compress:
        raw = gzip.open(path, "wb")
    else:
        raw = open(path, "wb")
    if bom:
        raw.write(b"\xef\xbb\xbf" if encoding.startswith("utf-8") else b"")
    stream = io.TextIOWrapper(raw, encoding=encoding, newline="")
    return stream


def write_delimited(
    path: Path,
    rows: int = DEFAULT_ROWS,
    *,
    delimiter: str = ",",
    encoding: str = "utf-8",
    bom: bool = False,
    compress: bool = False,
    latin1_safe: bool = False,
    header: list[str] | None = None,
    variant: str = "",
) -> Path:
    """Write the population as a delimited file.

    ``variant`` injects structural dirt that only a text container can carry:

    ``ragged``      rows with too few and too many fields
    ``dup_header``  the same column name twice
    ``trailing``    blank trailing rows and a blank trailing column
    """
    latin1 = latin1_safe or encoding.lower() in {"latin-1", "latin1", "iso-8859-1"}
    cols = header or list(COLUMNS)
    if variant == "dup_header":
        cols = cols + ["note"]
    if variant == "trailing":
        cols = cols + [""]
    stream = _open_text(path, encoding, compress=compress, bom=bom)
    try:
        writer = csv.writer(stream, delimiter=delimiter, lineterminator="\n")
        writer.writerow(cols)
        for rec in iter_rows_text(rows, latin1_safe=latin1):
            row = [rec[c] for c in COLUMNS]
            if variant == "dup_header":
                row = row + [rec["note"]]
            elif variant == "trailing":
                row = row + [""]
            elif variant == "ragged":
                i = int(rec["id"])
                if i % 25000 == 0:
                    row = row[:6]           # too few fields
                elif i % 25000 == 12500:
                    row = row + ["extra1", "extra2"]  # too many fields
            writer.writerow(row)
        if variant == "trailing":
            for _ in range(5):
                writer.writerow(["" for _ in cols])
    finally:
        stream.close()
    return path


def write_json(path: Path, rows: int = DEFAULT_ROWS) -> Path:
    with open(path, "w", encoding="utf-8") as f:
        f.write("[\n")
        for n, rec in enumerate(iter_rows_text(rows)):
            if n:
                f.write(",\n")
            f.write(json.dumps(rec, ensure_ascii=False))
        f.write("\n]\n")
    return path


def write_jsonl(path: Path, rows: int = DEFAULT_ROWS) -> Path:
    with open(path, "w", encoding="utf-8") as f:
        for rec in iter_rows_text(rows):
            f.write(json.dumps(rec, ensure_ascii=False))
            f.write("\n")
    return path


def write_xml(path: Path, rows: int = DEFAULT_ROWS) -> Path:
    from xml.sax.saxutils import escape

    with open(path, "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n<records>\n')
        for rec in iter_rows_text(rows):
            f.write("  <record>")
            for col in COLUMNS:
                f.write(f"<{col}>{escape(rec[col])}</{col}>")
            f.write("</record>\n")
        f.write("</records>\n")
    return path


def write_yaml(path: Path, rows: int = DEFAULT_ROWS) -> Path:
    """YAML sequence of mappings — quoted scalars, no external dependency."""
    def _q(value: str) -> str:
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

    with open(path, "w", encoding="utf-8") as f:
        for rec in iter_rows_text(rows):
            f.write("- " + f"{COLUMNS[0]}: {_q(rec[COLUMNS[0]])}\n")
            for col in COLUMNS[1:]:
                f.write(f"  {col}: {_q(rec[col])}\n")
    return path


def write_fixed_width(path: Path, rows: int = DEFAULT_ROWS) -> Path:
    """Padded, delimiter-free records — the layout is ``FIXED_WIDTH_LAYOUT``."""
    with open(path, "w", encoding="utf-8", newline="") as f:
        for rec in iter_rows_text(rows):
            line = "".join(
                str(rec[col]).replace("\n", " ").replace("\t", " ")[:width].ljust(width)
                for col, width in FIXED_WIDTH_LAYOUT
            )
            f.write(line + "\n")
    return path


def _arrow_table(rows: int, *, batch: int = 20000):
    """Arrow batches with native types — decimal stays decimal, ts stays ts."""
    import pyarrow as pa

    schema = pa.schema([
        ("id", pa.int64()),
        ("acct_code", pa.string()),
        ("amount", pa.decimal128(18, 4)),
        # qty is a *string* column on purpose: the fixture's non-numeric cell
        # has to survive the container so the writer is the thing that decides
        # to quarantine it.
        ("qty", pa.string()),
        ("note", pa.string()),
        ("unicode_name", pa.string()),
        ("created_at", pa.timestamp("us", tz="UTC")),
        ("dob_mixed", pa.string()),
        ("flag", pa.bool_()),
        ("null_empty", pa.string()),
        ("null_token", pa.string()),
    ])
    cols: dict[str, list[Any]] = {c: [] for c in COLUMNS}
    for rec in iter_rows_text(rows):
        cols["id"].append(int(rec["id"]))
        cols["acct_code"].append(rec["acct_code"])
        cols["amount"].append(Decimal(rec["amount"]).quantize(Decimal("0.0001")))
        cols["qty"].append(rec["qty"])
        cols["note"].append(rec["note"])
        cols["unicode_name"].append(rec["unicode_name"])
        cols["created_at"].append(datetime.fromisoformat(rec["created_at"]))
        cols["dob_mixed"].append(rec["dob_mixed"])
        cols["flag"].append(rec["flag"] == "true")
        cols["null_empty"].append(rec["null_empty"])
        cols["null_token"].append(rec["null_token"])
        if len(cols["id"]) >= batch:
            yield pa.table({c: cols[c] for c in COLUMNS}, schema=schema)
            cols = {c: [] for c in COLUMNS}
    if cols["id"]:
        yield pa.table({c: cols[c] for c in COLUMNS}, schema=schema)


def write_parquet(path: Path, rows: int = DEFAULT_ROWS) -> Path:
    import pyarrow.parquet as pq

    writer = None
    try:
        for table in _arrow_table(rows):
            if writer is None:
                writer = pq.ParquetWriter(str(path), table.schema)
            writer.write_table(table)
    finally:
        if writer is not None:
            writer.close()
    return path


def write_orc(path: Path, rows: int = DEFAULT_ROWS) -> Path:
    import pyarrow as pa
    import pyarrow.orc as orc

    tables = list(_arrow_table(rows))
    orc.write_table(pa.concat_tables(tables), str(path))
    return path


AVRO_SCHEMA: dict[str, Any] = {
    "type": "record",
    "name": "DirtyRow",
    "fields": [
        {"name": "id", "type": "long"},
        {"name": "acct_code", "type": "string"},
        {
            "name": "amount",
            "type": {"type": "bytes", "logicalType": "decimal", "precision": 18, "scale": 4},
        },
        {"name": "qty", "type": "string"},
        {"name": "note", "type": "string"},
        {"name": "unicode_name", "type": "string"},
        {"name": "created_at", "type": {"type": "long", "logicalType": "timestamp-micros"}},
        {"name": "dob_mixed", "type": "string"},
        {"name": "flag", "type": "boolean"},
        {"name": "null_empty", "type": "string"},
        {"name": "null_token", "type": "string"},
    ],
}


def write_avro(path: Path, rows: int = DEFAULT_ROWS) -> Path:
    import fastavro

    def _records() -> Iterator[dict[str, Any]]:
        for rec in iter_rows_text(rows):
            yield {
                "id": int(rec["id"]),
                "acct_code": rec["acct_code"],
                "amount": Decimal(rec["amount"]).quantize(Decimal("0.0001")),
                "qty": rec["qty"],
                "note": rec["note"],
                "unicode_name": rec["unicode_name"],
                "created_at": datetime.fromisoformat(rec["created_at"]),
                "dob_mixed": rec["dob_mixed"],
                "flag": rec["flag"] == "true",
                "null_empty": rec["null_empty"],
                "null_token": rec["null_token"],
            }

    parsed = fastavro.parse_schema(AVRO_SCHEMA)
    with open(path, "wb") as f:
        fastavro.writer(f, parsed, _records())
    return path


def write_excel(
    path: Path,
    rows: int = DEFAULT_ROWS,
    *,
    variant: str = "",
) -> Path:
    """Write .xlsx with openpyxl's write-only mode.

    ``variant='trailing'`` adds the Excel classic: blank trailing rows and a
    blank trailing column that formatting left behind. Those phantom rows must
    not arrive as NULL rows in the destination.
    """
    from openpyxl import Workbook
    from openpyxl.cell import WriteOnlyCell

    wb = Workbook(write_only=True)
    ws = wb.create_sheet("data")
    header = list(COLUMNS) + ([""] if variant == "trailing" else [])
    ws.append(header)
    for rec in iter_rows_text(rows):
        cells = []
        for col in COLUMNS:
            cell = WriteOnlyCell(ws, value=rec[col])
            # Text format everywhere: Excel would otherwise turn 0000007 into 7
            # and 1.2345E+3 into a float. The fixture's claim is the text.
            cell.number_format = "@"
            cells.append(cell)
        if variant == "trailing":
            cells.append(WriteOnlyCell(ws, value=None))
        ws.append(cells)
    if variant == "trailing":
        for _ in range(5):
            ws.append([None] * len(header))
    wb.save(str(path))
    return path


def write_format(kind: str, path: Path, rows: int = DEFAULT_ROWS) -> Path:
    """Write the population in ``kind`` (a key of ``FORMATS``)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if kind in _DELIMITERS:
        return write_delimited(path, rows, delimiter=_DELIMITERS[kind])
    if kind == "csv_gz":
        return write_delimited(path, rows, compress=True)
    if kind == "json":
        return write_json(path, rows)
    if kind in {"jsonl", "ndjson"}:
        return write_jsonl(path, rows)
    if kind == "xml":
        return write_xml(path, rows)
    if kind == "yaml":
        return write_yaml(path, rows)
    if kind == "fixed_width":
        return write_fixed_width(path, rows)
    if kind == "parquet":
        return write_parquet(path, rows)
    if kind == "orc":
        return write_orc(path, rows)
    if kind == "avro":
        return write_avro(path, rows)
    if kind == "excel":
        return write_excel(path, rows)
    raise ValueError(f"unknown fixture format {kind!r}")


#: Structural / encoding variants, proven on the containers that can carry them.
STRUCTURAL_VARIANTS: dict[str, dict[str, Any]] = {
    "csv_bom": {"format": "csv", "kwargs": {"bom": True}},
    "csv_utf16": {"format": "csv", "kwargs": {"encoding": "utf-16"}},
    "csv_latin1": {"format": "csv", "kwargs": {"encoding": "latin-1", "latin1_safe": True}},
    "csv_ragged": {"format": "csv", "kwargs": {"variant": "ragged"}},
    "csv_dup_header": {"format": "csv", "kwargs": {"variant": "dup_header"}},
    "excel_trailing": {"format": "excel", "kwargs": {"variant": "trailing"}},
}


def write_variant(name: str, path: Path, rows: int = DEFAULT_ROWS) -> Path:
    spec = STRUCTURAL_VARIANTS[name]
    path.parent.mkdir(parents=True, exist_ok=True)
    if spec["format"] == "excel":
        return write_excel(path, rows, **spec["kwargs"])
    return write_delimited(path, rows, **spec["kwargs"])


# --------------------------------------------------------------------------- #
# Independent readers — used to verify a destination *file*, never to write one.
# --------------------------------------------------------------------------- #


def read_delimited(path: Path, *, delimiter: str = ",", encoding: str = "utf-8") -> list[dict[str, Any]]:
    opener = gzip.open if str(path).endswith(".gz") else open
    with opener(path, "rt", encoding=encoding, newline="") as f:  # type: ignore[operator]
        return list(csv.DictReader(f, delimiter=delimiter))


def read_json_file(path: Path) -> list[dict[str, Any]]:
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data if isinstance(data, list) else [data]


def read_jsonl_file(path: Path) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


def read_arrow(path: Path, *, orc_format: bool = False) -> list[dict[str, Any]]:
    if orc_format:
        import pyarrow.orc as orc

        table = orc.read_table(str(path))
    else:
        import pyarrow.parquet as pq

        table = pq.read_table(str(path))
    return table.to_pylist()


def read_avro_file(path: Path) -> list[dict[str, Any]]:
    import fastavro

    with open(path, "rb") as f:
        return list(fastavro.reader(f))


def _excel_cell_value(cell: Any) -> Any:
    """Recover ``''`` from a typed-but-textless cell.

    xlsx does carry the distinction: an empty text cell is written as a typed
    string cell with no run (``<c t="inlineStr"/>``) while an absent value has no
    ``<c>`` at all. ``openpyxl`` reports both as ``None`` through ``.value``, so
    reading values only would flatten a preserved ``''`` into NULL and accuse the
    writer of a loss that is not in the file.
    """
    value = cell.value
    if value is None and cell.data_type in {"s", "str", "inlineStr"}:
        return ""
    return value


def read_excel_file(path: Path) -> list[dict[str, Any]]:
    from openpyxl import load_workbook

    wb = load_workbook(str(path), read_only=True, data_only=True)
    ws = wb[wb.sheetnames[0]]
    rows = ws.iter_rows()
    header = [str(c.value) if c.value is not None else "" for c in next(rows)]
    out: list[dict[str, Any]] = []
    for row in rows:
        values = [_excel_cell_value(c) for c in row]
        if all(v is None for v in values):
            continue
        out.append({h: v for h, v in zip(header, values) if h})
    wb.close()
    return out


def read_xml_file(path: Path) -> list[dict[str, Any]]:
    from defusedxml.ElementTree import parse

    tree = parse(str(path))
    out: list[dict[str, Any]] = []
    for record in tree.getroot():
        out.append({child.tag: (child.text if child.text is not None else "") for child in record})
    return out


def read_export(path: Path, export_format: str) -> list[dict[str, Any]]:
    """Parse an exported file with a reader that is not the product's writer."""
    fmt = (export_format or "").lower()
    if fmt == "csv":
        return read_delimited(path)
    if fmt == "tsv":
        return read_delimited(path, delimiter="\t")
    if fmt == "json":
        return read_json_file(path)
    if fmt in {"jsonl", "ndjson"}:
        return read_jsonl_file(path)
    if fmt == "parquet":
        return read_arrow(path)
    if fmt == "orc":
        return read_arrow(path, orc_format=True)
    if fmt == "avro":
        return read_avro_file(path)
    if fmt == "excel":
        return read_excel_file(path)
    if fmt == "xml":
        return read_xml_file(path)
    raise ValueError(f"no independent reader for export format {fmt!r}")


def read_bytes_as(export_format: str, payload: bytes, *, suffix: str = "") -> list[dict[str, Any]]:
    """Parse export bytes (object-store payloads) with the same readers."""
    import tempfile

    fmt = (export_format or "").lower()
    with tempfile.NamedTemporaryFile(suffix=suffix or f".{fmt}", delete=False) as tmp:
        tmp.write(payload)
        tmp_path = Path(tmp.name)
    try:
        return read_export(tmp_path, fmt)
    finally:
        os.unlink(tmp_path)


def fixed_width_parse(path: Path) -> list[dict[str, Any]]:
    """Reference parse of the fixed-width fixture, using the declared layout."""
    out: list[dict[str, Any]] = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            rec: dict[str, Any] = {}
            pos = 0
            for col, width in FIXED_WIDTH_LAYOUT:
                rec[col] = line[pos : pos + width].rstrip()
                pos += width
            out.append(rec)
    return out
