"""One 100K-row dirty-data population, written in every file format we claim.

Every format in the matrix carries the *same* rows, so a checksum difference
between two cells is a fidelity defect and not a fixture difference. The
population is generated by code (never committed) and is deterministic: row *i*
has the same cells on every host and in every format.

What "dirty" means here, and what each kind of dirt is expected to do:

===================================== =========================================
embedded delimiter / quote / newline  legal RFC-4180 content — must round-trip
UTF-8 / latin-1 / UTF-16 + BOM        must decode, never mojibake
leading-zero identifiers (``0000007``)must stay text, never become ``7``
decimals in scientific notation       must land at full declared scale
several date spellings in one column  must stay text, never be reinterpreted
very long strings (10 KiB)            must not be truncated
nulls as empty / ``NULL`` / ``\\N``    measured per format, never guessed
non-numeric cell in a numeric column  must be **quarantined**, not coerced
ragged rows / duplicate headers       structural — see ``STRUCTURAL_VARIANTS``
blank trailing Excel rows / columns   phantom rows must not become NULL rows
===================================== =========================================

The population is intentionally free of dirt that cannot be expressed in a
typed container (Parquet/Avro/ORC cannot hold a ragged row), so the format grid
compares like with like; structural dirt is proven on the formats that can
carry it, as its own cells.
"""

from __future__ import annotations

import csv
import gzip
import hashlib
import io
import json
import os
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import datetime, timezone
from decimal import Decimal
from pathlib import Path
from typing import Any, Callable, Iterable, Iterator

DEFAULT_ROWS = int(os.getenv("DATAFLOW_SCALE_ROWS", "100000"))

#: Column order is part of the fixture identity — checksums are positional.
COLUMNS: tuple[str, ...] = (
    "id",
    "acct_code",
    "amount",
    "qty",
    "note",
    "unicode_name",
    "created_at",
    "dob_mixed",
    "flag",
    "null_empty",
    "null_token",
)

#: Declared destination types. ``qty`` is INTEGER on purpose: the fixture puts a
#: non-numeric cell in it so the writer has to quarantine those rows instead of
#: NULLing or truncating them. ``created_at`` carries three different UTC
#: offsets, so a destination that drops the offset lands a different instant and
#: the checksum says so.
DEST_TYPES: dict[str, str] = {
    "id": "BIGINT",
    "acct_code": "VARCHAR(32)",
    "amount": "DECIMAL(18,4)",
    "qty": "INTEGER",
    "note": "TEXT",
    "unicode_name": "VARCHAR(200)",
    "created_at": "TIMESTAMPTZ",
    "dob_mixed": "VARCHAR(32)",
    "flag": "BOOLEAN",
    "null_empty": "VARCHAR(64)",
    "null_token": "VARCHAR(64)",
}


def dest_types(dialect: str = "") -> dict[str, str]:
    """Declared destination types for one dialect.

    MySQL has no timezone-aware carrier — ``DATETIME`` is naive and the engine
    refuses a tz-aware value into it rather than silently dropping the offset
    (correct, and proven as its own cell). The honest MySQL declaration for a
    column of offset-bearing instants is therefore text, which preserves the
    offset instead of losing it.
    """
    types = dict(DEST_TYPES)
    if dialect.lower() in {"mysql", "mariadb"}:
        types["created_at"] = "VARCHAR(40)"
    return types


#: Null spellings are *measured*, not asserted: a delimited file's ``NULL`` text
#: and a JSON string ``"NULL"`` are different claims, and the matrix records
#: what each format actually landed rather than encoding a guess as an
#: expectation. ``null_token`` therefore stays out of the compared projection.
CHECKSUM_COLUMNS: tuple[str, ...] = tuple(c for c in COLUMNS if c != "null_token")

# Row-index modulus for each kind of dirt. Coprime-ish spacing keeps the kinds
# from stacking on the same row, so one failure names one cause.
_DIRT_NOTE = 1000       # embedded delimiter + quote + newline
_DIRT_LONG = 9000       # 10 KiB string
_DIRT_SCI = 7000        # scientific-notation decimal
_DIRT_QUARANTINE = 11000  # non-numeric cell in the INTEGER column
_DIRT_EMPTY = 5000      # empty string (must stay '', never NULL)
_DIRT_TOKEN = 3000      # literal NULL / \N spellings

_LONG_STRING = "L" * 10_000
_EMBEDDED = 'He said "hi", then\nleft; a|b\tc'
_UNICODE_NAMES = ("Ana Muñoz", "北京市データ", "Zoë Ω", "Jose Peña 🌍")
_LATIN1_NAMES = ("Ana Muñoz", "Zoë", "Jose Peña", "Réunion")
_DOB_SPELLINGS = ("2024-01-05", "05/01/2024", "01-05-2024", "5 Jan 2024", "20240105")
_OFFSETS = ("+00:00", "+05:30", "-08:00")

QUARANTINE_VALUE = "N/A"


def is_quarantine_row(i: int) -> bool:
    """True when row *i* carries the non-numeric cell that must be held out."""
    return i % _DIRT_QUARANTINE == 0


def quarantine_row_count(rows: int = DEFAULT_ROWS) -> int:
    return rows // _DIRT_QUARANTINE


def retained_row_count(rows: int = DEFAULT_ROWS) -> int:
    """Rows a quarantining destination must hold after the run."""
    return rows - quarantine_row_count(rows)


def row_text(i: int, *, latin1_safe: bool = False) -> dict[str, str]:
    """Row *i* (1-based) in its text form — what a delimited file carries."""
    names = _LATIN1_NAMES if latin1_safe else _UNICODE_NAMES
    if i % _DIRT_SCI == 0:
        amount = "1.2345E+3"
    else:
        amount = f"{(i % 100000) + 0.1234:.4f}"
    if i % _DIRT_LONG == 0:
        note = _LONG_STRING
    elif i % _DIRT_NOTE == 0:
        note = _EMBEDDED
    else:
        note = f"row {i}"
    qty = QUARANTINE_VALUE if is_quarantine_row(i) else str(i % 500)
    null_empty = "" if i % _DIRT_EMPTY == 0 else "ok"
    if i % _DIRT_TOKEN == 0:
        null_token = "NULL" if (i // _DIRT_TOKEN) % 2 else "\\N"
    else:
        null_token = f"t{i % 97}"
    hour, minute, second = i % 24, i % 60, (i * 7) % 60
    offset = _OFFSETS[i % len(_OFFSETS)]
    return {
        "id": str(i),
        "acct_code": f"{i:07d}",
        "amount": amount,
        "qty": qty,
        "note": note,
        "unicode_name": names[i % len(names)],
        "created_at": (
            f"2024-{(i % 12) + 1:02d}-{(i % 28) + 1:02d}"
            f"T{hour:02d}:{minute:02d}:{second:02d}{offset}"
        ),
        "dob_mixed": _DOB_SPELLINGS[i % len(_DOB_SPELLINGS)],
        "flag": "true" if i % 2 == 0 else "false",
        "null_empty": null_empty,
        "null_token": null_token,
    }


def iter_rows_text(rows: int = DEFAULT_ROWS, *, latin1_safe: bool = False) -> Iterator[dict[str, str]]:
    for i in range(1, rows + 1):
        yield row_text(i, latin1_safe=latin1_safe)


# --------------------------------------------------------------------------- #
# Canonicalization — one function for the expected value and the read-back
# value, so a checksum comparison cannot pass by comparing two different
# renderings of the same cell.
# --------------------------------------------------------------------------- #

_NULL = "<NULL>"


def _canon_amount(value: Any) -> str:
    if value is None:
        return _NULL
    return str(Decimal(str(value)).quantize(Decimal("0.0001")))


def _canon_timestamp(value: Any) -> str:
    if value is None:
        return _NULL
    if isinstance(value, datetime):
        dt = value
    else:
        text = str(value).strip().replace(" ", "T")
        if text.endswith("Z"):
            text = text[:-1] + "+00:00"
        dt = datetime.fromisoformat(text)
    if dt.tzinfo is not None:
        dt = dt.astimezone(timezone.utc).replace(tzinfo=None)
    return dt.isoformat(sep="T", timespec="seconds")


def _canon_bool(value: Any) -> str:
    if value is None:
        return _NULL
    if isinstance(value, bool):
        return "true" if value else "false"
    text = str(value).strip().lower()
    if text in {"true", "t", "1", "yes", "y"}:
        return "true"
    if text in {"false", "f", "0", "no", "n"}:
        return "false"
    return f"<UNPARSED:{text}>"


def _canon_int(value: Any) -> str:
    if value is None:
        return _NULL
    if isinstance(value, str) and not value.strip():
        return _NULL
    return str(int(Decimal(str(value))))


def _canon_text(value: Any) -> str:
    if value is None:
        return _NULL
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


_CANON: dict[str, Callable[[Any], str]] = {
    "id": _canon_int,
    "acct_code": _canon_text,
    "amount": _canon_amount,
    "qty": _canon_int,
    "note": _canon_text,
    "unicode_name": _canon_text,
    "created_at": _canon_timestamp,
    "dob_mixed": _canon_text,
    "flag": _canon_bool,
    "null_empty": _canon_text,
    "null_token": _canon_text,
}


_EMPTY_OR_NULL = "<EMPTY_OR_NULL>"
_ambiguous_empty = False


@contextmanager
def empty_is_ambiguous() -> Iterator[None]:
    """Compare ``''`` and NULL as one value in the ``null_empty`` column.

    RFC 4180 has no NULL: a delimited file writes an empty text cell as nothing,
    so ``''`` and "absent" are the same bytes and no destination can honestly
    recover the difference. Inside this context the compared projection folds the
    two, and the per-cell null tally still records which spelling the destination
    actually holds. Formats that *do* carry the distinction (JSON, Excel,
    Parquet, Avro, ORC, XML) are compared strictly, outside this context.
    """
    global _ambiguous_empty
    previous = _ambiguous_empty
    _ambiguous_empty = True
    try:
        yield
    finally:
        _ambiguous_empty = previous


def canonical_cells(record: dict[str, Any], columns: Iterable[str] = CHECKSUM_COLUMNS) -> tuple[str, ...]:
    """Canonical text for the compared projection of one row."""
    out: list[str] = []
    for col in columns:
        raw = record.get(col)
        if col == "null_empty" and _ambiguous_empty and (raw is None or raw == ""):
            out.append(_EMPTY_OR_NULL)
            continue
        try:
            out.append(_CANON[col](raw))
        except Exception:  # noqa: BLE001 — an unparseable cell is evidence, not a crash
            out.append(f"<UNPARSED:{raw!r}>")
    return tuple(out)


def checksum_rows(
    records: Iterable[dict[str, Any]],
    columns: Iterable[str] = CHECKSUM_COLUMNS,
) -> tuple[str, int]:
    """``(sha256, row_count)`` over the canonical projection, id-ordered.

    Rows are hashed in ``id`` order so a destination that returns them in a
    different physical order still checksums the same — order is not the claim,
    content is.
    """
    cols = tuple(columns)
    keyed: list[tuple[int, tuple[str, ...]]] = []
    for rec in records:
        cells = canonical_cells(rec, cols)
        try:
            key = int(Decimal(str(rec.get("id"))))
        except Exception:  # noqa: BLE001
            key = -1
        keyed.append((key, cells))
    keyed.sort(key=lambda item: item[0])
    digest = hashlib.sha256()
    for _key, cells in keyed:
        digest.update("\x1f".join(cells).encode("utf-8"))
        digest.update(b"\x1e")
    return digest.hexdigest(), len(keyed)


def expected_checksum(
    rows: int = DEFAULT_ROWS,
    *,
    latin1_safe: bool = False,
    include_quarantined: bool = False,
) -> tuple[str, int]:
    """Checksum a correct destination must hold after the run."""
    def _gen() -> Iterator[dict[str, str]]:
        for rec in iter_rows_text(rows, latin1_safe=latin1_safe):
            if include_quarantined or not is_quarantine_row(int(rec["id"])):
                yield rec

    return checksum_rows(_gen())


def null_token_expectation(rows: int = DEFAULT_ROWS) -> dict[str, int]:
    """How many retained rows carry each ``null_token`` spelling."""
    counts = {"NULL": 0, "\\N": 0, "value": 0}
    for i in range(1, rows + 1):
        if is_quarantine_row(i):
            continue
        token = row_text(i)["null_token"]
        if token in counts:
            counts[token] += 1
        else:
            counts["value"] += 1
    return counts


